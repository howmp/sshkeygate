// parsedIcons caches the parsed SVGs, which ui.MustParseSVG reads once.
var parsedIcons = map[string]*ui.SVG{}

// icon returns the parsed SVG for one of the constants above.
func icon(svg string) *ui.SVG {
	if parsed, ok := parsedIcons[svg]; ok {
		return parsed
	}
	parsed := ui.MustParseSVG([]byte(svg))
	parsedIcons[svg] = parsed
	return parsed
}

// sidebarIcon is the kind of an icon in the navigation list.
type sidebarIcon int

// The navigation icons.
const (
	iconKey sidebarIcon = iota
	iconImport
	iconShield
	iconSettings
	iconLog
)

// svg returns the SVG of a navigation icon.
func (k sidebarIcon) svg() string {
	switch k {
	case iconImport:
		return svgImport
	case iconShield:
		return svgShield
	case iconSettings:
		return svgSettings
	case iconLog:
		return svgLog
	default:
		return svgKey
	}
}

// drawIcon shows a navigation icon in the given colour.
func drawIcon(c *ui.Context, kind sidebarIcon, colour ui.Color) ui.Element {
	return ui.Icon(c, icon(kind.svg())).FontSize(17).TextColor(colour)
}
